  var lang = (function () {
    try {
      var l = localStorage.getItem('app_lang');
      return SUPPORTED.indexOf(l) >= 0 ? l : 'vi';
    } catch (e) { return 'vi'; }
  })();

  function t(key, vars) {
    var s = (DICT[lang] && DICT[lang][key]) || DICT.vi[key] || key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split('{' + k + '}').join(String(vars[k]));
      });
    }
    return s;
  }

  function applyI18n() {
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
    });
    var titleEl = document.querySelector('[data-i18n-title]');
    if (titleEl) document.title = t(titleEl.getAttribute('data-i18n-title'));
    document.documentElement.lang = lang;
  }

  function setLang(l) {
    if (SUPPORTED.indexOf(l) < 0) return;
    lang = l;
    try { localStorage.setItem('app_lang', l); } catch (e) {}
    applyI18n();
  }

  window.I18N = {
    t: t,
    getLang: function () { return lang; },
    setLang: setLang,
    apply: applyI18n,
    SUPPORTED: SUPPORTED,
    DICT: DICT
  };
  window.t = t;

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyI18n);
  } else {
    applyI18n();
  }
